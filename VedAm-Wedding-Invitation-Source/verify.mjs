import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const root=path.resolve('.');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'app.js'),'utf8');
const css=['styles.css'].map(f=>fs.readFileSync(path.join(root,f),'utf8')).join('\n');
assert.equal((html.match(/<section\b/g)||[]).length,9,'Exactly nine sections');
assert.equal((html.match(/role="tab"/g)||[]).length,3,'Exactly three ceremonies');
assert(!/Sangeet|RSVP|Guest Essentials|SCREEN 0/i.test(html),'Excluded sections must stay excluded');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(ids.length,new Set(ids).size,'Unique IDs');
for(const match of html.matchAll(/(?:src|href)="([^"#]+)"/g)){
  if(/^https?:/.test(match[1]))continue;
  assert(fs.existsSync(path.join(root,match[1].split('?')[0])),`Missing asset ${match[1]}`);
}
for(const match of css.matchAll(/url\(['"]?(assets\/[^)'" ]+)/g))assert(fs.existsSync(path.join(root,match[1])));
for(const href of html.matchAll(/href="#([^"]+)"/g))assert(ids.includes(href[1]),`Broken anchor ${href[1]}`);
assert(!/screen-0\d\.(webp|png)/.test(html),'Do not embed flattened mockup screens');
assert(css.includes('prefers-reduced-motion'));
assert(html.includes('25 January 2026')&&!html.includes('26 January 2026'),'Correct engagement date');
assert(html.includes('Two hearts, one journey')&&!html.includes('Story to be added'),'Finished milestone caption');
assert((html.match(/#VedAm/g)||[]).length>=3&&!html.includes('A · V'),'Consistent exact-case hashtag');
assert(!/Granddaughter|Grandson|Bhupendra|Sarojini|Vijay Kr\./.test(html),'Grandparent details removed');
assert(html.includes('compact-parents')&&html.includes('compact-names'),'Compact parent-led invitation restored');
assert(!html.includes('dock-monogram'),'No footer branding strip');
assert(html.includes('id="live-petals"')&&js.includes('buildPetalStream'),'Persistent viewport petal stream');
assert(css.includes('music-revolve')&&css.includes('peacock-neck'),'Revolving music and articulated peacocks');
assert(!/class="lotus-mark gallery-/.test(html),'No duplicated gallery lotus');
for(const asset of ['v3-opening.webp','v3-hero.webp','v5-formal.webp','v3-countdown.webp','v3-herons.webp','v3-medallion.webp','v3-lotus.webp'])assert(html.includes(asset),'Missing corrected artwork');
assert(html.includes('id="invitation" hidden inert'),'Invitation must be gated behind the seal');
assert(!js.includes('if(location.hash&&'),'Initial hash must not bypass the opening');
assert(js.includes('setPointerCapture'),'Gesture should retain pointer tracking');
assert(css.includes('.floating-controls{left:auto;'),'Controls must float at the bottom right without a footer bar');
for(const query of ['Shakuntala+Niwas%2C+Sunderpur%2C+Varanasi','Hotel+De+Paris%2C+The+Mall+Road%2C+Varanasi+Cantonment'])assert(html.includes(query),'Missing authoritative Maps location');
const calSource=js.slice(js.indexOf('const calendarEvents='),js.indexOf("$('#add-calendar').addEventListener"));
const sandbox={TextEncoder,Date,SITE_URL:'https://example.test/'};vm.createContext(sandbox);
const calendar=vm.runInContext(calSource+'\ncalendarText()',sandbox);
assert.equal((calendar.match(/BEGIN:VEVENT/g)||[]).length,3);
const bundledCalendar=fs.readFileSync(path.join(root,'assets/Amulya-and-Vedant-Celebrations.ics'),'utf8');
assert.equal((bundledCalendar.match(/BEGIN:VEVENT/g)||[]).length,3);
for(const dt of ['20261124T050000Z','20261126T033000Z','20261126T140000Z'])assert(bundledCalendar.includes('DTSTART:'+dt),'Bundled calendar start');
for(const dt of ['20261124T050000Z','20261126T033000Z','20261126T140000Z'])assert(calendar.includes('DTSTART:'+dt));
assert(calendar.endsWith('END:VCALENDAR\r\n'));
assert(!calendar.includes('DTEND'),'No invented ceremony end times');
const unfolded=calendar.replace(/\r\n /g,'');
assert(unfolded.includes('Shakuntala Niwas\\, Sunderpur\\, Varanasi'));
for(const line of calendar.split('\r\n'))assert(Buffer.byteLength(line)<=75,'RFC 5545 octet folding');
assert.equal(Date.parse('2026-11-26T19:30:00+05:30'),Date.parse('2026-11-26T14:00:00Z'));
console.log('PASS: nine sections, three ceremonies, anchors, unique IDs, all assets, no flattened mockup screens, reduced motion, and three valid calendar events in IST.');
